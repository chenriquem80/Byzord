export const labels: LabelRecord[] = products.flatMap((product) =>
  product.manufacturers.flatMap((manufacturer) =>
    stores.map((store) => {
      const firstCompatibility = product.compatibilities[0];
      const inventory = manufacturer.inventories.find((item) => item.storeId === store.id);

      return {
        id: `lbl-${product.id}-${manufacturer.id}-${store.id}`,
        storeId: store.id,
        storeName: store.name,
        productCode: product.internalCode,
        productName: product.name,
        glassType: product.glassType,
        vehicleLabel: `${product.brand} ${firstCompatibility?.model ?? ""}`.trim(),
        yearRange: firstCompatibility
          ? `${firstCompatibility.startYear}/${firstCompatibility.endYear}`
          : "-",
        feature: product.feature.toLowerCase(),
        manufacturer: manufacturer.manufacturer.toLowerCase(),
        purchaseSummary: `${Math.round(manufacturer.price)} - ${new Date(manufacturer.lastPurchaseDate).getMonth() + 1}/${new Date(manufacturer.lastPurchaseDate).getFullYear()}`,
        location: inventory?.location ?? "Sem localização",
        qrCode: `https://autovitrais.local/produtos/${product.id}?loja=${store.id}&fabricante=${manufacturer.manufacturer}`,
        barcode: product.barcode,
      };
    }),
  ),
);

